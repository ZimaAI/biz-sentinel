#!/usr/bin/env python3
"""Browser checks for offline HTML, using set_content to avoid sandbox navigation policy.
Dependency: playwright plus an installed Chromium. No external network, model or server.
"""
from pathlib import Path
import json,os
from playwright.sync_api import sync_playwright
R=Path(__file__).resolve().parents[1];checks=[];errors=[];shots=R/'previews';shots.mkdir(exist_ok=True)
def ok(name,value=True):
 checks.append({'name':name,'passed':bool(value)})
 if not value:raise AssertionError(name)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
 context=browser.new_context(viewport={'width':1600,'height':1100},device_scale_factor=1,accept_downloads=True)
 page=context.new_page();page.set_default_timeout(5000)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content((R/'prototype/index.html').read_text(),wait_until='load')
 ok('overview GMV from fixture',page.locator('[data-kpi=gmv]').inner_text()=='¥486,200.00')
 ok('overview net receipts',page.locator('[data-kpi=net]').inner_text()=='¥459,340.00')
 page.screenshot(path=str(shots/'01-overview.png'),full_page=True)
 page.locator('#scope').select_option('s1')
 ok('scope filters GMV',page.locator('[data-kpi=gmv]').inner_text()=='¥255,000.00')
 page.locator('#period').select_option('week')
 value=page.evaluate('CommerceLensDemo.snapshot("s1","week").current.gmv')
 ok('7-day aggregation differs from one day',value>25500000)
 page.locator('#scope').select_option('all');page.locator('#period').select_option('day')
 page.locator('[data-chart=orders]').click();ok('chart can switch measure','订单数' in page.locator('.chart').get_attribute('aria-label'))
 page.locator('[data-chart=gmv]').click()
 for state in ['loading','empty','error','forbidden']:
  page.locator('#ui-state').select_option(state)
  ok('state '+state+' hides business KPI',page.locator('[data-kpi]').count()==0)
  page.locator('[data-action=reset-state]').click()
 page.locator('#ui-state').select_option('partial')
 ok('missing refunds do not become 0',page.locator('[data-kpi=refund]').inner_text()=='—' and page.locator('[data-kpi=net]').inner_text()=='—')
 page.locator('#ui-state').select_option('normal')
 page.locator('[data-action=diagnose]').click()
 ok('plan requires explicit approval',page.evaluate('CommerceLensDemo.state().run.status')=='WAITING_APPROVAL')
 page.locator('[data-action=approve-dialog]').click();ok('approval scope modal visible',page.locator('.modal').is_visible())
 page.locator('[data-approve-version]').click()
 page.wait_for_function('CommerceLensDemo.state().run.status === "SUCCEEDED"')
 ok('6 simulated steps complete',page.evaluate('CommerceLensDemo.state().run.step')==6)
 page.wait_for_timeout(3550)
 page.screenshot(path=str(shots/'02-analysis.png'),full_page=True)
 page.locator('[data-evidence=E-004]').click()
 ok('inventory evidence SKU amounts correct','252,000.00' in page.locator('.drawer-content').inner_text() and '153,000.00' in page.locator('.drawer-content').inner_text())
 page.locator('[data-drawer-tab=sql]').click();ok('SQL template is explicitly not executed','未执行' in page.locator('.drawer-content').inner_text())
 page.screenshot(path=str(shots/'03-evidence.png'),full_page=True)
 page.keyboard.press('Escape');ok('Escape closes evidence',page.locator('.drawer').count()==0)
 page.locator('#scope').select_option('s2')
 page.locator('[data-action=open-run-report]').click()
 ok('report scope frozen when global filter changes',page.locator('[data-report-scope]').get_attribute('data-report-scope')=='all')
 with page.expect_download() as info:page.locator('[data-action=export-report]').click()
 download=info.value;download.save_as(str(R/'evaluation/exported-report-sample.md'))
 text=(R/'evaluation/exported-report-sample.md').read_text()
 ok('Markdown export preserves actual figures','486,200.00' in text and '合成数据' in text)
 page.wait_for_timeout(3550);page.screenshot(path=str(shots/'04-report.png'),full_page=True)
 page.locator('.nav-btn[data-nav=metrics]').click();page.locator('#metric-search').fill('净收款')
 ok('metric search filters rows',page.locator('tr[data-metric]').count()==1)
 page.locator('tr[data-metric=net_receipts]').click();ok('metric boundary visible','不是利润' in page.locator('aside.card').inner_text())
 page.locator('#metric-search').fill('');page.screenshot(path=str(shots/'05-metrics.png'),full_page=True)
 page.locator('.nav-btn[data-nav=data]').click();ok('8 CSV table rows shown',page.locator('tbody tr').count()==8)
 page.locator('[data-action=import-dialog]').click();ok('import not falsely declared connected','不在此页伪造上传成功' in page.locator('.modal').inner_text());page.keyboard.press('Escape')
 page.screenshot(path=str(shots/'06-data.png'),full_page=True)
 page.locator('.nav-btn[data-nav=anomalies]').click();page.locator('[data-action=rule-dialog]').click()
 page.locator('#rule-relative').fill('-1');page.locator('[data-action=save-rule]').click();ok('invalid rule value rejected',bool(page.locator('#rule-error').inner_text()))
 page.locator('#rule-relative').fill('99');page.locator('[data-action=save-rule]').click();ok('rule change affects preview','未触发' in page.locator('.anomaly-card').first.inner_text())
 page.locator('.nav-btn[data-nav=analysis]').click();page.locator('[data-question=sku-refund]').click();page.locator('[data-action=prepare]').click()
 ok('unsupported SKU refund refused','不支持 SKU 退款分析' in page.locator('.notice').inner_text())
 page.locator('#question').fill('销售额下降了吗？');page.locator('[data-action=prepare]').click();ok('ambiguous sales asks clarification','需要澄清指标口径' in page.locator('.notice').inner_text())
 page.locator('[data-action=clarify-gmv]').click();page.locator('[data-action=approve-dialog]').click();page.locator('[data-approve-version]').click()
 page.locator('[data-action=cancel-run]').click();page.wait_for_timeout(850)
 ok('cancel stops simulation',page.evaluate('CommerceLensDemo.state().run.status')=='CANCELLED' and page.evaluate('CommerceLensDemo.state().run.step')<6)
 page.locator('.nav-btn[data-nav=runs]').click();ok('audit displays simulated events',page.locator('tbody tr').count()>=3)
 page.screenshot(path=str(shots/'07-runs.png'),full_page=True)
 page.locator('.nav-btn[data-nav=overview]').click()
 for width in [1440,1024,800,390]:
  page.set_viewport_size({'width':width,'height':900});page.wait_for_timeout(50)
  dims=page.evaluate('({scroll:document.documentElement.scrollWidth,width:window.innerWidth})')
  ok('overview no horizontal viewport overflow at '+str(width),dims['scroll']<=dims['width'])
 page.locator('[data-action=mobile]').click();ok('mobile navigation opens',page.locator('.sidebar').evaluate('(e)=>e.classList.contains("mobile-open")'))
 page.locator('.nav-btn[data-nav=metrics]').click();ok('mobile navigation selects page','指标字典' in page.locator('h1').inner_text())
 page.locator('[data-action=mobile]').click();page.locator('.nav-btn[data-nav=overview]').click()
 page.wait_for_timeout(3700)
 ok('mobile navigation closes after route selection',not page.locator('.sidebar').evaluate('(e)=>e.classList.contains("mobile-open")'))
 page.screenshot(path=str(shots/'08-mobile.png'),full_page=True)
 ok('no unhandled browser JavaScript errors',not errors)
 browser.close()
result={'kind':'offline-prototype-browser','passed':len(checks),'failed':0,'checks':checks,'pageErrors':errors,'browser':'installed Chromium via Playwright','loadMethod':'page.set_content(single_file_html)','navigationLimit':'Environment blocks file:// and localhost navigation with ERR_BLOCKED_BY_ADMINISTRATOR; file opening and HTTP delivery were not validated. All inline JS/CSS DOM interactions rendered using set_content.','notTested':['real API','real SSE','live model','Nuxt build','actual access control','physical device']}
(R/'evaluation/prototype-validation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'passed':len(checks),'failed':0,'pageErrors':errors},ensure_ascii=False))
